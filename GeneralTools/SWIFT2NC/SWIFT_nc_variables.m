function airpres = checkAirPressure(airpres, ~)
% Air pressure is written as hPa (mbar, as readSWIFT_SBD, reprocess_PB2/WXT
% and L3_highresSWIFT give it), so check it is around atmospheric pressure.
% Onboard SBD values seem to be in bar. 0 marks bursts without it.
medianPressure = median(airpres(airpres ~= 0), 'omitnan');
if medianPressure < 800 || medianPressure > 1100
    error('SWIFT2NC:airpres', ['airpres median is %g, not atmospheric pressure in mbar (800-1100); ' ...
        'onboard SBD values seem to be in bar'], medianPressure);
end
end


function spectra = clipSpectra(spectra, variableDefinition)
% preProcessData for wavespectra. spectra is flatSWIFT.wavespectra: each
% per-frequency field (freq, energy, a1, ...) is [nFreq x nTimes],
% NaN-padded. Bursts have e.g. 42 or 85 bins, so:
%   1. every field is clipped to its first nbins rows (freq.nbins), or
%      NaN-padded to nbins
%   2. the frequency grid is taken from the first burst with nbins
%      increasing frequencies and a check factor
%   3. bursts without check (old SWIFT2NC dropped these) or with other
%      frequencies (more than freqTolerance off, e.g. all-zero
%      placeholders) become NaN
% Returns [] (and warns) if no burst can give the grid.
nbins = variableDefinition.freq.nbins;
freqTolerance = 1e-4; % Hz, bin spacing is ~0.01 Hz
nFreqIn = size(spectra.freq, 1);
freq = clipRows(spectra.freq, nbins);
hasCheck = false(1, size(freq, 2));
if isfield(spectra, 'check')
    hasCheck = any(~isnan(spectra.check), 1);
end
gridBurst = find(all(~isnan(freq), 1) & all(diff(freq) > 0, 1) & hasCheck, 1);
if isempty(gridBurst)
    warnNoTrace('SWIFT2NC:noSpectra', ...
        'No burst has %d increasing wave frequencies and a check factor, wavespectra not written', nbins);
    spectra = [];
    return
end
% note this assumes the first freq is good/correct, should this be a constant defined somewhere?
freqGrid = freq(:, gridBurst);
isOffGrid = ~hasCheck | any(abs(freq - freqGrid) > freqTolerance, 1);
isDropped = isOffGrid & any(~isnan(freq), 1);
if any(isDropped)
    warnNoTrace('SWIFT2NC:offGrid', ...
        '%d burst(s) without check or with wavespectra.freq not on the %d-bin grid, written as NaN', ...
        sum(isDropped), nbins);
end

fieldNames = fieldnames(spectra);
for fieldIndex = 1:numel(fieldNames)
    fieldName = fieldNames{fieldIndex};
    if size(spectra.(fieldName), 1) ~= nFreqIn
        continue % only fields given per frequency
    end
    values = clipRows(spectra.(fieldName), nbins);
    values(:, isOffGrid) = NaN;
    spectra.(fieldName) = values;
end
spectra.freq = repmat(freqGrid, 1, size(freq, 2));
end


function values = clipRows(values, n)
% First n rows of values, NaN-padded if there are fewer
values(end+1:n, :) = NaN;
values = values(1:n, :);
end


function warnNoTrace(varargin)
% warning() without the "In ... at line ..." stack trace
backtrace = warning('off', 'backtrace');
warning(varargin{:});
warning(backtrace);
end
