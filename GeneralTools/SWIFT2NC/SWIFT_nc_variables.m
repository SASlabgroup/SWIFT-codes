function [S, platforms, globals] = SWIFT_nc_variables()
% Variable definitions (whitelist) for SWIFT2NC
%
%   [S, platforms, globals] = SWIFT_nc_variables()
%
% S mirrors the SWIFT struct tree. Each leaf is the variable definition of
% that field: its netCDF attributes, plus the settings below. Only fields
% defined here are written.
%
% Settings, not written as attributes. SWIFT2NC (writeNCVariables) has its
% own list of these names to leave out of the attributes, so a new setting
% must be added there too, or it is written as an attribute:
%   name        netCDF variable name, the name the old SWIFT2NC used
%               (default: SWIFT field name, as old SWIFT2NC did for
%               anything it did not rename)
%   coordinate  true if the field defines a dimension (z, zHR, freq,
%               echoz); see Coordinates and data fields below
%   dim         on a coordinate: the name of the dimension it defines,
%               where it differs from its netCDF name (echoz -> zecho).
%               On a field with several values per burst: the dimension
%               it is written on, either a coordinate's (e.g. 'z') or one
%               shared by the fields that name it (e.g. 'obs_sample').
%               Without dim, such a field gets its own <name>_n dimension.
%   preProcessData  function handle, called before writing as
%               values = preProcessData(values, variableDefinition)
%               to check the field and return it, possibly changed, or []
%               to leave it out (warning why). values is the field as
%               flattenSWIFT gives it, one column per burst:
%                 numbers   [nPerBurst x nTimes] double, NaN-padded
%                 text      [1 x nTimes] string
%                 substruct (e.g. wavespectra) a struct of such arrays
%               variableDefinition is this entry of S (for a substruct,
%               the definitions of its fields). The functions are at the
%               end of this file.
%   nbins       wavespectra.freq only: number of frequency bins written
%   timeUnits   time only: 'days' (as old SWIFT2NC) or 'seconds' since
%               1970-01-01 (more standard non-matlab)
%
% Coordinates and data fields:
%   A coordinate defines a dimension and is written once on it, e.g.
%   z(z): each row (bin) has the same value in every burst. If its values
%   change between bursts (echoz, sound speed corrected) it is written as
%   (time, zecho) instead, and the fields on that dimension name it in
%   their CF coordinates attribute. Coordinates have no fill value.
%   A data field with several values per burst (e.g. profile.east) defines
%   no dimension: it is written on the one its dim names, e.g. east with
%   'dim','z' becomes east(time, z), and must have the same length.
%
% Dimensions (fields are [n x time], one column per burst):
%   time          one per burst
%   freq          wavespectra.freq, clipped to nbins; energy, a1, ... use it
%   z             signature.profile.z (v4), or uplooking.z / downlooking.z
%                 (v3; both at once is an error, they would share the name)
%   zHR           signature.HRprofile.z, named zHR as in old SWIFT2NC
%   zecho         signature.echoz, which varies per burst, so it is itself
%                 a (time, zecho) variable named in echo's coordinates
%   obs_sample    shared by the OBS_* fields (as old SWIFT2NC)
%   puck_channel  the three puck fluorometer channels
%   <name>_n      any other field with several values per burst (e.g.
%                 watertemp from several CTs)
%
% Attribute values may contain {key} placeholders, filled from
% platforms.(v3|v4|micro); an attribute that resolves to '' is omitted.
% {at_ct_depth} and {at_met_height} are ' at 0.66 m depth' style phrases
% made from SWIFT.CTdepth and SWIFT.metheight (set in readSWIFT_SBD),
% listing every distinct value (' at 0.18, 0.66, 1.22 m depth' for three
% CTs), or '' when the data has no height.
% globals are global attributes, with the same placeholders.
%
% Oct 2026 by M. LeClair (using claude); metadata ported from SWIFT2NC

